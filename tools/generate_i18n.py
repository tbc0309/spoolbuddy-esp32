"""Compile referenced upstream i18n keys plus explicit local supplements for LVGL."""
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
    upstream={lang:json.loads((ROOT/f'vendor/spoolbuddy/i18n/{lang}.json').read_text(encoding='utf-8')) for lang in ('en','zh-CN')}
    defaults=json.loads((ROOT/'vendor/spoolbuddy/i18n/defaults.json').read_text(encoding='utf-8'))
    upstream['en']={**defaults,**upstream['en']}
    local={lang:json.loads((ROOT/f'locales/{lang}.json').read_text(encoding='utf-8')) for lang in ('en','zh-CN')}
    keys=set()
    for file in (ROOT/'src/ui').glob('*'):
        if file.suffix in ('.c','.h'):
            keys.update(re.findall(r'\btr\("([\w.]+)"\)',file.read_text(encoding='utf-8')))
    keys.update(json.loads((ROOT/'locales/ui-keys.json').read_text(encoding='utf-8')))
    keys.update(local['en'])
    keys.update(local['zh-CN'])
    rows=[]
    for key in sorted(keys):
        en=local['en'].get(key,upstream['en'].get(key))
        zh=local['zh-CN'].get(key,upstream['zh-CN'].get(key))
        if not en or not zh: raise ValueError(f'Missing locale: {key}')
        # printf contracts cannot be changed by a translation.
        spec=r'%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?[hlz]*[sdiufg]'
        if re.findall(spec,en)!=re.findall(spec,zh):raise ValueError(f'Format mismatch: {key}')
        rows.append('    {'+', '.join(json.dumps(x,ensure_ascii=False) for x in (key,en,zh))+'},')
    (ROOT/'assets/i18n_catalog.h').write_text('// Generated by tools/generate_i18n.py; edit locales, not this file.\n'+ '\n'.join(rows)+'\n',encoding='utf-8')
    print(f'Generated {len(rows)} bilingual i18n entries')
if __name__=='__main__':generate()
